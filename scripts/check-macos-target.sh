#!/usr/bin/env bash
#
# Type-check DiskMate's macOS-specific code against the Apple target from any
# host.
#
# `cargo check --target aarch64-apple-darwin` on the real crate fails away from
# a Mac, because the bundled SQLite has to be compiled by an Apple toolchain.
# The macOS code that is actually risky is not SQLite: it is the libc bindings,
# the `statfs` field names, the Mach VM structures and the property-list
# parsing. All of that is pure Rust and can be checked anywhere.
#
# So this assembles a scratch crate that compiles the real
# `src/platform/macos/*.rs` files with stand-ins for the parts of the engine
# that pull in SQLite, and lints that for aarch64-apple-darwin.
#
# It runs clippy with warnings denied rather than a plain `cargo check`, because
# the macOS CI job does, and a lint that only fires on files Linux never
# compiles is exactly the failure this script is for.
#
# It is not a substitute for building on a Mac. It catches the class of mistake
# that is otherwise invisible until someone opens the project on one.
#
# Keep your toolchain current before trusting a pass: clippy gains lints with
# each release, and CI uses whatever `stable` is on the day. A local toolchain
# several releases behind will report clean on code CI rejects.
#   rustup update stable
#
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
ROOT="$PWD"
CORE="$ROOT/crates/diskmate-core/src"
TARGET="${1:-aarch64-apple-darwin}"

if ! rustup target list --installed | grep -qx "$TARGET"; then
  echo "==> Installing the $TARGET standard library"
  rustup target add "$TARGET"
fi

if ! cargo clippy --version >/dev/null 2>&1; then
  echo "error: clippy is not installed. Run: rustup component add clippy" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/src"

cat > "$WORK/Cargo.toml" <<EOF
[package]
name = "diskmate-macos-check"
version = "0.0.0"
edition = "2021"

[lib]
path = "src/lib.rs"

[dependencies]
serde = { version = "1", features = ["derive"] }
libc = "0.2"
plist = { version = "1.7", default-features = false }
EOF

cat > "$WORK/src/lib.rs" <<EOF
//! Generated by scripts/check-macos-target.sh. Do not edit.
#![allow(dead_code, unused_imports)]

pub mod error {
    use std::path::PathBuf;
    #[derive(Debug)]
    pub enum CoreError {
        Invalid(String),
        Io { path: PathBuf, source: std::io::Error },
        Unsupported { feature: &'static str },
    }
    impl std::fmt::Display for CoreError {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { write!(f, "{self:?}") }
    }
    impl std::error::Error for CoreError {}
    impl CoreError {
        pub fn io(path: impl Into<PathBuf>, source: std::io::Error) -> Self {
            Self::Io { path: path.into(), source }
        }
        pub fn invalid(msg: impl Into<String>) -> Self { Self::Invalid(msg.into()) }
    }
    pub type Result<T, E = CoreError> = std::result::Result<T, E>;
}

pub mod db { pub fn now_unix() -> i64 { 0 } }

#[path = "$CORE/model/mod.rs"]
pub mod model;

pub mod platform {
    use crate::error::Result;
    use crate::model::{MemorySnapshot, StartupItem, VolumeInfo};

    pub trait SystemProbe: Send + Sync {
        fn name(&self) -> &'static str;
        fn volumes(&self) -> Result<Vec<VolumeInfo>>;
        fn memory(&self) -> Result<MemorySnapshot>;
        fn startup_items(&self) -> Result<Vec<StartupItem>>;
        fn skip_mount_points(&self, root: &std::path::Path) -> Vec<std::path::PathBuf>;
    }

    #[path = "$CORE/platform/startup_locations.rs"]
    pub mod startup_locations;

    #[path = "$CORE/platform/protected.rs"]
    pub mod protected;

    pub(crate) mod unix_util {
        use std::ffi::CStr;
        use std::path::Path;
        pub(crate) fn c_string(raw: &[libc::c_char]) -> String {
            unsafe { CStr::from_ptr(raw.as_ptr()) }.to_string_lossy().into_owned()
        }
        pub(crate) fn volume_name(mount_point: &str) -> String {
            if mount_point == "/" { return "System".to_string(); }
            Path::new(mount_point)
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_else(|| mount_point.to_string())
        }
        pub(crate) fn is_readable(mount_point: &str) -> bool {
            std::fs::read_dir(mount_point).is_ok()
        }
    }

    #[path = "$CORE/platform/macos/mod.rs"]
    pub mod macos;
}
EOF

echo "==> Linting src/platform/macos for $TARGET"
cd "$WORK"
cargo clippy --target "$TARGET" --all-targets -- -D warnings

echo
echo "macOS platform code type-checks and lints clean for $TARGET."
echo "Building the app itself still requires a Mac with the Xcode Command Line Tools."
